/** Разбивает сырой многострочный текст на отдельные пункты — каждая
 *  непустая строка (после переноса) становится одним пунктом списка.
 *  Пустые строки (лишние переносы при наборе) не создают пустых
 *  записей. Общий разбор для всех "текст с переносами → список пунктов"
 *  полей обложки — coverNews (см. NewsBlock.tsx) и dayInHistory (см.
 *  ContentsGrid.tsx): один и тот же формат ввода не должен разбираться
 *  двумя независимыми копиями одной и той же функции. */
export function splitLines(raw: string): string[] {
  return raw
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0);
}
